"""Collect complete licence texts for a binding's target-specific Cargo closure."""

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICE_FILES = ("LICENSE-MIT", "LICENSE-APACHE", "NOTICE", "THIRD-PARTY-NOTICES.txt")
LICENSE_NAME = re.compile(
    r"^(?:licen[cs]e|copying|copyright|notice|unlicense)(?:$|[-._])", re.IGNORECASE
)


def dependency_closure(metadata: dict, package: str) -> list[dict]:
    """Include normal/build dependencies, including proc macros; exclude test-only crates."""
    packages = {item["id"]: item for item in metadata["packages"]}
    roots = [item["id"] for item in packages.values() if item["name"] == package]
    if len(roots) != 1:
        raise ValueError(f"expected one Cargo package named {package!r}")
    nodes = {item["id"]: item for item in metadata["resolve"]["nodes"]}
    seen = {roots[0]}
    pending = [roots[0]]
    while pending:
        for dep in nodes[pending.pop()]["deps"]:
            if any(kind["kind"] in (None, "build") for kind in dep["dep_kinds"]):
                if dep["pkg"] not in seen:
                    seen.add(dep["pkg"])
                    pending.append(dep["pkg"])
    seen.remove(roots[0])
    return sorted((packages[key] for key in seen), key=lambda item: (item["name"], item["version"]))


def license_files(package: dict) -> list[Path]:
    directory = Path(package["manifest_path"]).parent
    files = {
        path
        for path in directory.rglob("*")
        if path.is_file()
        and (
            LICENSE_NAME.match(path.name)
            or any(
                part.lower() in ("licenses", "licences")
                for part in path.relative_to(directory).parts[:-1]
            )
        )
    }
    if package.get("license_file"):
        files.add(directory / package["license_file"])
    if not files:
        raise ValueError(
            f"no licence/notice files found for {package['name']} {package['version']}"
        )
    return sorted(files, key=lambda path: path.relative_to(directory).as_posix())


def render_notices(metadata: dict, package: str, target: str) -> bytes:
    dependencies = dependency_closure(metadata, package)
    if not dependencies:
        raise ValueError("no dependency notices generated")
    sections = [
        f"Cargo dependency licences and notices for {package}\nTarget: {target}\n"
        "Generated by scripts/collect_binding_notices.py from cargo metadata --locked.\n"
        "Normal and build dependencies are included; test-only dependencies are excluded.\n"
        "Crate-local notices retain their scope, attribution, and unresolved provenance.\n"
    ]
    for dependency in dependencies:
        directory = Path(dependency["manifest_path"]).parent
        sections.append(
            f"\n{'=' * 72}\n{dependency['name']} {dependency['version']}\n"
            f"SPDX: {dependency.get('license') or 'see licence file'}\n"
        )
        for path in license_files(dependency):
            sections.append(f"\n--- {path.relative_to(directory).as_posix()} ---\n")
            sections.append(path.read_text(encoding="utf-8") + "\n")
    return "".join(sections).encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", required=True, choices=("nazuchem-python", "nazuchem-wasm"))
    parser.add_argument("--target", help="Rust target triple (defaults to rustc host)")
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    target = args.target
    if target is None:
        version = subprocess.check_output(["rustc", "-vV"], text=True, cwd=ROOT)
        target = next(
            line.removeprefix("host: ")
            for line in version.splitlines()
            if line.startswith("host: ")
        )
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
            cwd=ROOT,
        )
    )
    notices = render_notices(metadata, args.package, target)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name in NOTICE_FILES[:-1]:
        shutil.copyfile(ROOT / name, args.output_dir / name)
    (args.output_dir / NOTICE_FILES[-1]).write_bytes(notices)
    count = len(dependency_closure(metadata, args.package))
    print(f"Collected {count} dependency crates into {args.output_dir / NOTICE_FILES[-1]}")


if __name__ == "__main__":
    main()

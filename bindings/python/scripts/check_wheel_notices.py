"""Verify generated binding notices and their exact bytes inside a wheel."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import ZipFile

PACKAGE_DIR = Path(__file__).resolve().parents[1]
ROOT = PACKAGE_DIR.parents[1]
NOTICE_FILES = ("LICENSE-MIT", "LICENSE-APACHE", "NOTICE", "THIRD-PARTY-NOTICES.txt")


def check_wheel(wheel: Path, generated_dir: Path, fresh_dir: Path) -> None:
    """Require fresh source files and one matching PEP 639 member per notice."""
    with ZipFile(wheel) as archive:
        members = archive.namelist()
        for name in NOTICE_FILES:
            source = generated_dir / name
            if not source.is_file() or source.stat().st_size == 0:
                raise ValueError(f"missing generated notice: {source}; run build_wheel.py first")
            expected = (fresh_dir / name).read_bytes()
            if source.read_bytes() != expected:
                raise ValueError(f"stale or ungenerated notice: {source}; run build_wheel.py first")
            matches = [
                member
                for member in members
                if len(Path(member).parts) == 3
                and Path(member).parts[0].endswith(".dist-info")
                and Path(member).parts[1:] == ("licenses", name)
            ]
            if len(matches) != 1:
                raise ValueError(f"expected exactly one .dist-info/licenses/{name} in {wheel}")
            if archive.read(matches[0]) != expected:
                raise ValueError(f"wheel notice differs from generated bytes: {name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wheel", type=Path)
    parser.add_argument("--target", help="Rust target triple used to build the wheel")
    args = parser.parse_args()
    for name in NOTICE_FILES:
        if not (PACKAGE_DIR / name).is_file():
            raise SystemExit(f"missing generated notice: {name}; run build_wheel.py first")
    with TemporaryDirectory(prefix="nazuchem-wheel-notices-") as temporary:
        fresh = Path(temporary)
        command = [
            sys.executable,
            str(ROOT / "scripts/collect_binding_notices.py"),
            "--package",
            "nazuchem-python",
            "--output-dir",
            str(fresh),
        ]
        if args.target:
            command.extend(["--target", args.target])
        subprocess.run(command, cwd=ROOT, check=True)
        try:
            check_wheel(args.wheel, PACKAGE_DIR, fresh)
        except ValueError as error:
            raise SystemExit(str(error)) from error
    print(f"Verified all four generated licence/notice files in {args.wheel}")


if __name__ == "__main__":
    main()

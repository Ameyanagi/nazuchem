"""Generate the target's notices, build an abi3 wheel, and verify its contents."""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import ZipFile

PACKAGE_DIR = Path(__file__).resolve().parents[1]
ROOT = PACKAGE_DIR.parents[1]
NOTICE_FILES = ("LICENSE-MIT", "LICENSE-APACHE", "NOTICE", "THIRD-PARTY-NOTICES.txt")


def generated_notices(directory: Path) -> dict[str, bytes]:
    """Read this build's fresh output; absent or empty generation must fail."""
    notices = {}
    for name in NOTICE_FILES:
        source = directory / name
        if not source.is_file() or source.stat().st_size == 0:
            raise ValueError(f"missing or empty generated notice: {source}")
        notices[name] = source.read_bytes()
    return notices


def check_wheel(wheel: Path, notices: dict[str, bytes]) -> None:
    """Require one PEP 639 member matching each freshly generated notice."""
    with ZipFile(wheel) as archive:
        for name in NOTICE_FILES:
            expected = notices.get(name)
            if not expected:
                raise ValueError(f"missing or empty generated notice: {name}")
            matches = [
                member
                for member in archive.namelist()
                if len(Path(member).parts) == 3
                and Path(member).parts[0].endswith(".dist-info")
                and Path(member).parts[1:] == ("licenses", name)
            ]
            if len(matches) != 1:
                raise ValueError(f"expected exactly one .dist-info/licenses/{name} in {wheel}")
            if archive.read(matches[0]) != expected:
                raise ValueError(f"wheel notice differs from generated bytes: {name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", help="Rust target triple (defaults to rustc host)")
    parser.add_argument("--release", action="store_true", help="enable Rust release optimization")
    parser.add_argument("--zig", action="store_true", help="use the pinned Zig linker via maturin")
    parser.add_argument("--compatibility", help="maturin platform compatibility policy")
    parser.add_argument("--out", type=Path, default=PACKAGE_DIR / "dist")
    args = parser.parse_args()
    environment = os.environ.copy()
    environment.setdefault("CARGO_TARGET_DIR", str(ROOT / "target"))
    args.out.mkdir(parents=True, exist_ok=True)
    # Fresh directories prevent stale notices or wheels from passing verification.
    with TemporaryDirectory(prefix="nazuchem-wheels-") as temporary:
        generated = Path(temporary) / "notices"
        collect = [
            sys.executable,
            str(ROOT / "scripts/collect_binding_notices.py"),
            "--package",
            "nazuchem-python",
            "--output-dir",
            str(generated),
        ]
        if args.target:
            collect.extend(["--target", args.target])
        subprocess.run(collect, cwd=ROOT, env=environment, check=True)
        notices = generated_notices(generated)
        for name in NOTICE_FILES:
            (PACKAGE_DIR / name).write_bytes(notices[name])
        build = [
            "uv",
            "run",
            "--no-project",
            "--with",
            "maturin>=1.8,<2",
        ]
        if args.zig:
            build.extend(["--with", "ziglang==0.17.1"])
        build.extend(
            [
                "maturin",
                "build",
                "--locked",
                "--manifest-path",
                str(PACKAGE_DIR / "Cargo.toml"),
                "--interpreter",
                sys.executable,
                "--out",
                temporary,
            ]
        )
        if args.target:
            build.extend(["--target", args.target])
        if args.release:
            build.append("--release")
        if args.zig:
            build.append("--zig")
        if args.compatibility:
            build.extend(["--compatibility", args.compatibility])
        subprocess.run(build, cwd=PACKAGE_DIR, env=environment, check=True)
        wheels = sorted(Path(temporary).glob("*.whl"))
        if not wheels:
            raise SystemExit("maturin did not produce a wheel")
        for wheel in wheels:
            check_wheel(wheel, notices)
            destination = args.out / wheel.name
            shutil.copyfile(wheel, destination)
            print(f"Built and checked {destination}")


if __name__ == "__main__":
    main()
